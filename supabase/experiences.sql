-- À exécuter une seule fois dans Supabase > SQL Editor.
do $$
begin
  create type public.experience_type as enum ('professional', 'education', 'other');
exception
  when duplicate_object then null;
end $$;

create table if not exists public.experiences (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text not null,
  organization text not null,
  location text,
  start_date date not null,
  end_date date,
  period_label text,
  current boolean not null default false,
  type public.experience_type not null,
  description text not null default '',
  link_url text,
  link_label text,
  published_at timestamptz,
  constraint experiences_dates_check check (end_date is null or end_date >= start_date),
  constraint experiences_current_check check (not current or end_date is null)
);

-- Permet aussi de mettre à niveau une table créée avec une ancienne version du script.
alter table public.experiences
  add column if not exists period_label text;

create index if not exists experiences_start_date_idx
  on public.experiences (start_date desc);

create unique index if not exists experiences_identity_idx
  on public.experiences (title, organization, start_date);

alter table public.experiences enable row level security;

drop policy if exists "Published experiences are publicly readable"
  on public.experiences;

create policy "Published experiences are publicly readable"
  on public.experiences
  for select
  to anon, authenticated
  using (published_at is not null);

grant select on table public.experiences to anon, authenticated;

